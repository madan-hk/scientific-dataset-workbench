"""
RNA-project's build step. Reads dataset metadata/tags/synonyms/QnA from
enrichment/ + samples/ and writes the app's data files into generated/.

RNA-project/ folder layout:
    workflow/    -- index.html (the app itself)
    generated/   -- data.js + samples_data.js, built by this script
    metadata/    -- original downloaded metadata (gtex/tcga/sra)
    enrichment/  -- tags.jsonl, sra_project_tags.jsonl, synonyms.json, qna_pilot.yaml
    samples/     -- samples.jsonl
    tasks/       -- one folder per task (task.json + one JSON per dataset),
                    written directly by the app via the File System Access
                    API -- this script never touches tasks/
    scripts/     -- this file + the rest of the pipeline

No LLM calls happen here or anywhere else in this build step -- everything
is built from already-extracted static data in enrichment/ + samples/.
qna_pilot.yaml (the one-time, already-generated pilot) is read as-is and
never regenerated by this script.

Produces generated/data.js: DATASETS (tags.jsonl, unchanged shape), SYNONYMS
(synonyms.json, unchanged shape), and QNA -- the pilot's answers from
qna_pilot.yaml. Datasets outside the pilot simply show no AI Extracted
Information block; there's no heuristic or LLM fallback for them. The old
heuristic generator (build_qna_for_project) is kept below only as dead
reference code, unused by main().

USAGE
-----
    cd scripts
    python3 build_data.py
"""
from __future__ import annotations
import json
import random
from collections import Counter
from pathlib import Path

import yaml

HERE = Path(__file__).parent
ROOT = HERE.parent
ENRICHED = ROOT / "enrichment"
SAMPLES_DIR = ROOT / "samples"
APP = ROOT / "generated"
TAGS_JSONL = ENRICHED / "tags.jsonl"
SAMPLES_JSONL = SAMPLES_DIR / "samples.jsonl"
SYNONYMS_JSON = ENRICHED / "synonyms.json"
OUT_JS = APP / "data.js"
OUT_SAMPLES_JS = APP / "samples_data.js"

QUESTIONS = [
    "What is the biological sample/source type?",
    "What is the sequencing/assay type?",
    "What organism/species are the samples from?",
    "What disease, condition, or biological state is being studied?",
    "What are the main experimental groups or sample groups?",
    "What is the study population?",
    "What is the experimental design?",
    "How many samples/subjects, and how are they distributed across groups?",
    "What are the important sample-level characteristics or variations?",
    "Most useful concise description of the dataset for a biologist?",
]
NOT_DETERMINABLE = "Not determinable from the available metadata."
SC_TERMS = ["single cell", "single-cell", "scrna", "10x genomics", "10x chromium", "droplet-based"]
SN_TERMS = ["single nucleus", "single-nucleus", "snrna"]
SPATIAL_TERMS = ["spatial transcriptomic", "visium", "spatial rna"]
SMALL_RNA_TERMS = ["small rna", "mirna-seq", "microrna"]
MOUSE_TERMS = ["mus musculus", "mouse", " mice "]
RAT_TERMS = ["rattus norvegicus", " rat "]
ADULT_TERMS = ["adult"]
PEDIATRIC_TERMS = ["pediatric", "paediatric", "child", "infant", "neonate"]


def load_tags():
    rows = []
    with TAGS_JSONL.open() as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    rows.sort(key=lambda r: (r["data_source"], r["project"]))
    return rows


def load_samples():
    by_project = {}
    if not SAMPLES_JSONL.exists():
        return by_project
    with SAMPLES_JSONL.open() as f:
        for line in f:
            line = line.strip()
            if line:
                row = json.loads(line)
                by_project[row["project"]] = row
    return by_project


def load_synonyms():
    if not SYNONYMS_JSON.exists():
        return {}
    return json.loads(SYNONYMS_JSON.read_text())


def tag_value(tags_row, category):
    for t in tags_row.get("tags", []):
        if t["category"] == category:
            return t["value"]
    return None


def study_text(study_info):
    return " ".join(v for v in study_info.values() if isinstance(v, str)).lower()


def any_term(text, terms):
    return any(t in text for t in terms)


def pick_subset(samples, project, k=5):
    rng = random.Random(project)
    return samples if len(samples) <= k else rng.sample(samples, k)


def build_qna_for_project(tags_row, samples_row):
    ds_source = tags_row["data_source"]
    n_samples = tags_row["n_samples"]
    study_info = (samples_row or {}).get("study_info", {}) or {}
    samples = (samples_row or {}).get("samples", []) or []
    text = study_text(study_info)
    subset = pick_subset(samples, tags_row["project"])

    tissue = tag_value(tags_row, "tissue")
    category = tag_value(tags_row, "tissue_category")
    specimen = tag_value(tags_row, "specimen")
    cell_line = tag_value(tags_row, "cell_line")
    if cell_line:
        source = f"Cell culture / cell line ({cell_line})."
    elif tissue:
        source = f"{tissue.title()} ({category})." if category else f"{tissue.title()}."
    elif specimen:
        source = f"{specimen.title()}."
    elif category:
        source = f"Category: {category}."
    else:
        source = NOT_DETERMINABLE

    if any_term(text, SPATIAL_TERMS):
        assay = "Spatial RNA-seq (keyword match in study text)."
    elif any_term(text, SN_TERMS):
        assay = "Single-nucleus RNA-seq (keyword match in study text)."
    elif any_term(text, SC_TERMS):
        assay = "Single-cell RNA-seq (keyword match in study text)."
    elif any_term(text, SMALL_RNA_TERMS):
        assay = "Small RNA-seq (keyword match in study text)."
    elif ds_source in ("gtex", "tcga"):
        assay = "Bulk RNA-seq (recount3 GTEx/TCGA processing is bulk)."
    else:
        assay = "Bulk RNA-seq (assumed default; not explicitly stated in study text)."

    organism = study_info.get("organism")
    if not organism:
        if any_term(text, MOUSE_TERMS):
            organism = "Mouse (Mus musculus) — keyword match in study text."
        elif any_term(text, RAT_TERMS):
            organism = "Rat (Rattus norvegicus) — keyword match in study text."
        elif ds_source in ("gtex", "tcga"):
            organism = "Human (Homo sapiens)."
        else:
            organism = "Not stated in metadata (default assumption: human)."

    disease = tag_value(tags_row, "disease")
    pathogen = tag_value(tags_row, "pathogen")
    if disease and pathogen:
        condition = f"{disease.title()}; pathogen of interest: {pathogen}."
    elif disease:
        condition = f"{disease.title()}."
    elif pathogen:
        condition = f"Infection/exposure model involving {pathogen}."
    elif ds_source == "gtex":
        condition = "None — GTEx is a healthy-donor reference cohort (post-mortem, non-diseased donors)."
    else:
        condition = NOT_DETERMINABLE

    if ds_source == "gtex":
        groups = "Single group — all donors are non-diseased reference tissue, no case/control split."
    elif ds_source == "tcga":
        types = Counter(s["raw"].get("cgc_sample_sample_type") for s in samples if s["raw"].get("cgc_sample_sample_type"))
        groups = ("By sample type: " + ", ".join(f"{v} {k}" for k, v in types.most_common()) + ".") if types \
            else "Tumor samples; no normal/control sample-type field present."
    else:
        hints = Counter(s.get("disease_hint") for s in samples if s.get("disease_hint"))
        if len(hints) > 1:
            groups = "Multiple conditions in metadata: " + ", ".join(f"{v} \"{k}\"" for k, v in hints.most_common(6)) + "."
        elif len(hints) == 1:
            (only,) = hints.keys()
            groups = f"Single condition group detected: \"{only}\". No distinct control arm found."
        else:
            groups = "No distinct groups could be identified from structured sample metadata."

    if ds_source == "gtex":
        ages = sorted(set(s["raw"].get("age") for s in samples if s["raw"].get("age")))
        population = "Adult donors (GTEx is a post-mortem adult donor program)." + (f" Age brackets: {', '.join(ages)}." if ages else "")
    elif ds_source == "tcga":
        ages = [a for a in (s["raw"].get("cgc_case_age_at_diagnosis") for s in samples) if isinstance(a, (int, float))]
        population = f"Adult cancer patients; age at diagnosis ranges {min(ages):.0f}–{max(ages):.0f} years." if ages \
            else "Adult cancer patients (age at diagnosis not present in this subset)."
    elif any_term(text, PEDIATRIC_TERMS):
        population = "Pediatric population indicated in study text."
    elif any_term(text, ADULT_TERMS):
        population = "Adult population indicated in study text."
    else:
        population = NOT_DETERMINABLE

    if ds_source == "gtex":
        design = "Cross-sectional reference collection — not a case-control or interventional design."
    elif ds_source == "tcga":
        design = "Case series with a subset of matched tumor/adjacent-normal samples." if "Normal" in groups \
            else "Case series of tumor samples; no matched-normal design evident."
    elif "Multiple conditions" in groups:
        design = "Appears to compare multiple conditions (case-control-like) based on disease_hint values."
    else:
        design = "Not determinable from the available metadata — no explicit design field."

    count_dist = f"{n_samples:,} total samples. Group distribution: {groups}"

    lines = []
    for s in subset:
        raw = s.get("raw", {})
        if ds_source == "gtex":
            bits = [f"age {raw.get('age')}" if raw.get("age") else None, f"sex code {raw.get('sex')}" if raw.get("sex") is not None else None]
        elif ds_source == "tcga":
            bits = [raw.get("cgc_sample_sample_type"), raw.get("gdc_cases.diagnoses.tumor_stage")]
        else:
            bits = [s.get("tissue_hint"), s.get("disease_hint"), raw.get("sample_title")]
        bits = [b for b in bits if b]
        lines.append(f"{s.get('run_id','?')}: " + (", ".join(str(b) for b in bits) if bits else "no distinguishing fields"))
    characteristics = " | ".join(lines) if lines else NOT_DETERMINABLE

    summary = (
        f"{tags_row['project']}: {source.rstrip('.')} samples, {organism.rstrip('.')}, "
        f"profiled by {assay.split(' (')[0].rstrip('.')}, studying {condition.rstrip('.')}. Design: {design.rstrip('.')}."
    )

    answers = [source, assay, organism, condition, groups, population, design, count_dist, characteristics, summary]
    return [[q, a] for q, a in zip(QUESTIONS, answers)]


PILOT_YAML = ENRICHED / "qna_pilot.yaml"


def load_pilot_qna():
    """The 15-dataset LLM pilot (5 each: GTEx/TCGA/SRA, n_samples>=100) from
    build_qna_llm.py. Real, LLM-generated answers -- noticeably better than
    the heuristic build_qna_for_project() above. Decision: 15 real answers
    beats 75 heuristic ones, so this is now the ONLY source for QNA -- no
    heuristic fallback for the other 60 datasets, they simply show no AI
    Extracted Information block."""
    if not PILOT_YAML.exists():
        return {}
    data = yaml.safe_load(PILOT_YAML.read_text()) or {}
    return {project: row["qna"] for project, row in data.items()}


def main():
    tags = load_tags()
    synonyms = load_synonyms()

    qna = load_pilot_qna()

    js = "// Auto-generated by build_data.py -- do not hand-edit. Re-run after tags.jsonl/synonyms.json/qna_pilot.yaml change.\n"
    js += "const DATASETS = " + json.dumps(tags, indent=2) + ";\n"
    js += "const SYNONYMS = " + json.dumps(synonyms, indent=2) + ";\n"
    js += "const QNA = " + json.dumps(qna, separators=(",", ":")) + ";\n"
    OUT_JS.write_text(js)
    print(f"Wrote {OUT_JS}: {len(tags)} datasets, {len(synonyms)} synonym entries, {len(qna)} QnA summaries.")

    # Per-sample data (Stage 4 sample curation table) is big -- kept in its
    # own file, loaded lazily via a dynamic <script> tag only when a
    # dataset's sample table is actually opened, so every other screen
    # doesn't pay for it upfront.
    samples_by_project = load_samples()
    by_project = {project: row["samples"] for project, row in samples_by_project.items()}
    total_samples = sum(len(v) for v in by_project.values())
    samples_js = "// Auto-generated by build_data.py -- lazy-loaded on demand, do not hand-edit.\n"
    samples_js += "const SAMPLES_BY_PROJECT = " + json.dumps(by_project, separators=(",", ":")) + ";\n"
    OUT_SAMPLES_JS.write_text(samples_js)
    print(f"Wrote {OUT_SAMPLES_JS}: {total_samples} samples across {len(by_project)} projects.")


if __name__ == "__main__":
    main()
